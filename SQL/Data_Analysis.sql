--DATA ANALYSIS

--1.TOTAL OUTSTANDING CREDIT BY YEAR 

SELECT YEAR,ROUND(SUM(OUTSTANDING_CREDIT_RS_CRORE),2) AS TOTAL_OUTSTANDING_IN_YEAR FROM CREDIT
GROUP BY YEAR
ORDER BY YEAR DESC

--2.TOTAL OUTSTANDING CREDIT BY BANK GROUP IN 2023

SELECT BANK_GROUP,ROUND(SUM(OUTSTANDING_CREDIT_RS_CRORE),2) AS TOTAL FROM CREDIT
WHERE YEAR = 2023
GROUP BY BANK_GROUP
ORDER BY TOTAL DESC


--3.TOTAL OUTSTANDING CREDIT BY SECTOR IN 2023

SELECT Sector_or_Occupation,ROUND(SUM(OUTSTANDING_CREDIT_RS_CRORE),2) AS TOTAL FROM CREDIT
WHERE YEAR = 2023
GROUP BY Sector_or_Occupation
ORDER BY TOTAL DESC


--4.FINDING TOP 10 STATES BY OUTSTANDING IN 2023

SELECT TOP 10 STATE,ROUND(SUM(OUTSTANDING_CREDIT_RS_CRORE),2) AS TOTAL FROM CREDIT 
WHERE YEAR = 2023
GROUP BY STATE
ORDER BY TOTAL DESC 

--5.TOTAL DEPOSIT BY YEAR 

SELECT YEAR,SUM(DEPOSIT_AMOUNT_RS_CRORE) AS TOTAL_DEPOSIT FROM DEPOSIT
GROUP BY YEAR
ORDER BY YEAR DESC

--6.TOTAL DEPOSITS BY REGION IN 2022

SELECT REGION,SUM(DEPOSIT_AMOUNT_RS_CRORE) AS TOTAL_DEPOSIT FROM DEPOSIT
WHERE YEAR = 2022
GROUP BY REGION
ORDER BY  TOTAL_DEPOSIT DESC

--7.TOTAL DEPOSITS BY POPULATION GROUP IN 2022

SELECT Population_Group,SUM(DEPOSIT_AMOUNT_RS_CRORE) AS TOTAL_DEPOSIT FROM DEPOSIT
WHERE YEAR = 2022
GROUP BY Population_Group
ORDER BY  TOTAL_DEPOSIT DESC


--8.BRANCHES OPENED BY YEAR


SELECT YEAR_OPENED,COUNT(*) AS TOTAL_BRANCHES FROM BRANCH
GROUP BY Year_Opened
ORDER BY COUNT(*) DESC


--9.BRANCHES OPENED BY BANK GROUP

SELECT Bank_Group,COUNT(*) AS TOTAL_BRANCHES FROM BRANCH
GROUP BY Bank_Group
ORDER BY COUNT(*) DESC


--10.TOP 10 STATES BY BRANCHES OPENED

SELECT TOP 10 STATE,COUNT(*) AS TOTAL_BRANCHES FROM BRANCH
GROUP BY STATE
ORDER BY COUNT(*) DESC





