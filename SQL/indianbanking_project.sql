use indianbanking


select * from credit
select * from Branch
select * from deposit
select * from reference


--VERIFY ROW COUNTS

SELECT COUNT(*) AS TOTAL_CREDITERS FROM CREDIT
SELECT COUNT(*) AS TOTAL_BRANCHES FROM BRANCH
SELECT COUNT(*) AS TOTAL_DEPOSITERS FROM DEPOSIT 
SELECT COUNT(*) AS REFERENCE FROM REFERENCE

--CHECKING DUPLICATE KEYS

SELECT RECORD_ID,COUNT(RECORD_ID) FROM CREDIT 
GROUP BY RECORD_ID
HAVING COUNT(RECORD_ID) > 1

SELECT RECORD_ID,COUNT(RECORD_ID) FROM DEPOSIT
GROUP BY RECORD_ID
HAVING COUNT(RECORD_ID) > 1

SELECT BRANCH_ID,COUNT(BRANCH_ID) FROM BRANCH 
GROUP BY BRANCH_ID
HAVING COUNT(BRANCH_ID) > 1

SELECT STATE_CODE,DISTRICT_CODE,COUNT(*) AS TOTAL FROM REFERENCE
GROUP BY STATE_CODE,DISTRICT_CODE
HAVING COUNT(*) > 1

--CHECKING FOR MISSING VALUES IN KEY COLUMNNS

SELECT SUM(CASE WHEN RECORD_ID IS NULL THEN 1 ELSE 0 END) AS MISSING_FLAG FROM CREDIT 
SELECT SUM(CASE WHEN RECORD_ID IS NULL THEN 1 ELSE 0 END) AS MISSING_FLAG FROM DEPOSIT
SELECT SUM(CASE WHEN BRANCH_ID IS NULL THEN 1 ELSE 0 END) AS MISSING_FLAG FROM BRANCH
SELECT SUM(CASE WHEN STATE_CODE IS NULL OR DISTRICT_CODE IS NULL THEN 1 ELSE 0 END) AS MISSING_FLAG FROM REFERENCE 