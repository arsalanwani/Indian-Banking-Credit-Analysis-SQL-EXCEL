--DATA CLEANING

--1.ZERO DEPOSIT ROWS IN DEPOSIT

SELECT COUNT(*) AS ZERO_DEPOSIT FROM DEPOSIT 
WHERE DEPOSIT_AMOUNT_RS_CRORE = 0   --133


--THERE  ARE 133 ZERO_DEPOSIT AMOUNT ROWS FOUND IN IT AND KEPT AS THEY ARE

--2.CHECKING ROWS WHERE OUTSTANDING IS MORE THAN THE LIMIT

SELECT COUNT(*) AS OUTSTANDING FROM CREDIT 
WHERE Outstanding_Credit_Rs_Crore > Credit_Limit_Rs_Crore --72

--72 ROWS HAVE OUTSTANDING HIGHER THAN THE LIMIT 

--3.ZERO CREDIT ROWS IN CREDIT

--3.1 HOW MANY ROWS HAVE OUTSTANDING CREDIT EQUAL TO

SELECT COUNT(*) AS ZERO_OUTSTANDING FROM CREDIT 
WHERE  Outstanding_Credit_Rs_Crore = 0   --202

--3.2 HOW MANY ROWS HAVE A CREDIT LIMIT EQUAL TO 0

SELECT COUNT(*) AS LIMIT_0 FROM CREDIT 
WHERE Credit_Limit_Rs_Crore = 0  --147

--202 ROWS HAVE 0 OUTSTANDING CREDIT WHILE AS 147 ROWS HAS 0 CREDIT LIMIT

--4.CHECKING BLANK AND DUPLICATE IFSC CODES IN BRANCH

--4.1 CHECKING BLANKS
SELECT COUNT(*) AS N0_IFSC FROM BRANCH 
WHERE IFSC_CODE IS NULL --302

--4.2 USED IFSC CODE WITH GROUP BY TO CHECK HOW MANY TIMES CODES REPEAT

SELECT IFSC_CODE,COUNT(*) AS TOTAL  FROM BRANCH 
GROUP BY IFSC_CODE
HAVING COUNT(*) > 1 

-- IFSC CODES CANNOT BE UNIQUE SO THEY ARE REPEATED MULTIPLE TIMES

--5.NEGATIVE VALUES IN CREDIT AND DEPOSIT

--5.1 NEGATIVE OUTSTANDING CREDIT IN CREDIT 
SELECT COUNT(*) AS NEGATIVE_OUTSTANDING FROM CREDIT 
WHERE Outstanding_Credit_Rs_Crore < 0 --0

--5.2 NEGATIVE CREDIT LIMIT IN CREDIT 
SELECT COUNT(*) AS NEGATIVE_OUTSTANDING FROM CREDIT 
WHERE Credit_Limit_Rs_Crore  < 0 --0

--5.3 NEGATIVE NUMBER OF ACCOUNTS IN CREDIT

SELECT COUNT(*) AS NEGATIVE_ACCOUNTS FROM CREDIT 
WHERE Number_of_Accounts < 0  --0

--5.4 NEGATIVE DEPOSIT AMOUNT IN DEPOSIT 

SELECT COUNT(*) AS NEGATIVE_DEPOSIT  FROM DEPOSIT 
WHERE Deposit_Amount_Rs_Crore < 0 --0

--5.5 NEGATIVE OFFICES IN DEPOSIT 

SELECT COUNT(*) AS NEGATIVE_OFFICES FROM DEPOSIT 
WHERE No_of_Offices < 0  --0

--NO NEGATIVE VALUES WERE FOUND

--6. CHECKING DUPLICATE NATURAL KEYS IN CREDIT 

SELECT COUNT(*) FROM CREDIT 
GROUP BY Year,State_Code,Bank_Group,Sector_or_Occupation
HAVING COUNT(*) > 1

--6.1 CHECKING DUPLICATE NATURAL KEYS IN DEPOSIT

SELECT COUNT(*) FROM DEPOSIT 
GROUP  BY year,state_code,district_code,Population_Group
having count(*) > 1


--7.CHECKING DISTRICTS FROM DEPOSIT THAT DO NOT MATCH REFERENCE

SELECT D.STATE,D.DISTRICT,D.DISTRICT_CODE,D.STATE_CODE FROM DEPOSIT D
LEFT JOIN REFERENCE R 
ON D.State_Code = R.State_Code 
AND D.District_Code = R.District_Code
WHERE R.DISTRICT IS NULL   --0

--7.1 CHECKING DISTRICTS FROM BRANCH THAT DO NOT MATCH REFERENCE

SELECT B.STATE_CODE,B.STATE,B.DISTRICT_CODE,B.DISTRICT FROM BRANCH B
LEFT JOIN REFERENCE R
ON R.DISTRICT_CODE=B.DISTRICT_CODE
AND R.STATE_CODE = B.STATE_CODE
WHERE R.DISTRICT IS NULL --0


--8.CHECKING DISTINCT VALUES AND RANGES

--8.1 CHECKING CREDIT 

SELECT DISTINCT YEAR FROM CREDIT
ORDER BY YEAR DESC

--8.2 CHECKING DEPOSIT

SELECT DISTINCT  YEAR FROM DEPOSIT 
ORDER BY YEAR DESC

--8.3 CHECKING BRANCH

SELECT DISTINCT YEAR_OPENED FROM BRANCH
ORDER BY YEAR_OPENED DESC

--8.4 CHECKING GROUPS AND CATEGORIES WITH DISTINCT 

--8.4.1 BANK GROUP IN CREDIT

SELECT BANK_GROUP,COUNT(*) AS TOTAL_ROWS FROM CREDIT 
GROUP BY BANK_GROUP
ORDER BY TOTAL_ROWS DESC
-- 6 GROUPS 


--8.4.2 SECTOR IN CREDIT 

SELECT Sector_or_Occupation, COUNT(*) AS Total_Rows
FROM CREDIT
GROUP BY Sector_or_Occupation
ORDER BY Total_Rows DESC
--8 GROUPS

-- 8.4.3 REGION IN DEPOSIT

SELECT Region, COUNT(*) AS Total_Rows
FROM DEPOSIT
GROUP BY Region
ORDER BY Total_Rows DESC
--6 GROUPS

-- 8.4.4 POPULATION GROUP IN DEPOSIT

SELECT Population_Group, COUNT(*) AS Total_Rows
FROM DEPOSIT
GROUP BY Population_Group
ORDER BY Total_Rows DESC
--4 GROUPS

-- 8.4.5 BANK GROUP IN BRANCH

SELECT Bank_Group, COUNT(*) AS Total_Rows
FROM BRANCH
GROUP BY Bank_Group
ORDER BY Total_Rows DESC
--5 GROUPS

-- 8.4.6 BRANCH TYPE IN BRANCH

SELECT Branch_Type, COUNT(*) AS Total_Rows
FROM BRANCH
