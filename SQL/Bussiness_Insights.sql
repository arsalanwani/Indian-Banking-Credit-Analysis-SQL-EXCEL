--1.CREDIT DEPOSITED RATIO BY YEAR

WITH CREDIT_BY_YEAR AS(
SELECT YEAR,ROUND(SUM(OUTSTANDING_CREDIT_RS_CRORE),2) AS TOTAL_CREDIT FROM CREDIT
WHERE YEAR BETWEEN 2019 AND 2022
GROUP BY YEAR
),
DEPOSIT_BY_YEAR AS (
SELECT YEAR,SUM(DEPOSIT_AMOUNT_RS_CRORE) AS TOTAL_DEPOSIT
FROM DEPOSIT
GROUP BY YEAR
)

SELECT C.YEAR,C.TOTAL_CREDIT,D.TOTAL_DEPOSIT,ROUND(C.TOTAL_CREDIT*100.0/D.TOTAL_DEPOSIT,2)AS CD_RATIO
FROM CREDIT_BY_YEAR C
JOIN DEPOSIT_BY_YEAR D
ON C.YEAR= D.YEAR
ORDER BY C.YEAR


--2.CREDIT DEPOSIT RATIO BY STATE  IN 2022

WITH CREDIT_TOTAL AS (
SELECT STATE,STATE_CODE,ROUND(SUM(OUTSTANDING_CREDIT_RS_CRORE),2) AS TOTAL_CREDIT,YEAR FROM CREDIT
WHERE YEAR = 2022
GROUP BY STATE,YEAR,STATE_CODE
),

DEPOSIT_TOTAL AS (
SELECT STATE,STATE_CODE,SUM(DEPOSIT_AMOUNT_RS_CRORE) AS TOTAL_DEPOSIT,YEAR FROM DEPOSIT
WHERE YEAR =2022
GROUP BY STATE_CODE,STATE,YEAR
)
SELECT TOP 10 C.STATE,C.STATE_CODE,C.YEAR,C.TOTAL_CREDIT,D.TOTAL_DEPOSIT,ROUND(C.TOTAL_CREDIT*100/D.TOTAL_DEPOSIT,2) AS CD_RATIO 
FROM CREDIT_TOTAL C
JOIN DEPOSIT_TOTAL D
ON D.YEAR=C.YEAR
AND D.STATE_CODE = C.STATE_CODE
ORDER BY CD_RATIO DESC

--3.TOP 10 DISTRICTS BY DEPOSITS IN 2022

WITH DEPOSITS AS (
SELECT  DISTRICT,STATE,REGION,SUM(DEPOSIT_AMOUNT_RS_CRORE) AS TOTAL_DEPOSIT FROM DEPOSIT
WHERE YEAR = 2022
GROUP BY DISTRICT,STATE,REGION
)
SELECT TOP 10  D.DISTRICT,D.STATE,D.REGION,D.TOTAL_DEPOSIT FROM DEPOSITS D
ORDER BY TOTAL_DEPOSIT DESC


--4.BRANCHES OPENED BY STATE WITH CREDIT IN 2023

WITH BRANCH_BY_STATE AS
(
SELECT STATE,STATE_CODE,COUNT(*) AS TOTAL_BRANCHES FROM BRANCH
GROUP BY STATE,STATE_CODE
),
CREDIT_2023 AS (
SELECT STATE,STATE_CODE,SUM(OUTSTANDING_CREDIT_RS_CRORE) AS TOTAL_CREDIT_2023 FROM CREDIT
WHERE YEAR = 2023
GROUP BY STATE,STATE_CODE
)

SELECT TOP 10 B.STATE,B.TOTAL_BRANCHES,C.TOTAL_CREDIT_2023 FROM BRANCH_BY_STATE  B
JOIN CREDIT_2023 C
ON B.STATE_CODE=C.STATE_CODE
ORDER BY B.TOTAL_BRANCHES DESC
